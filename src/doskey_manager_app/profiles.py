from pathlib import Path

from .config import command_prefix
from .paths import APP_DIR, LOADER_PATH, PROFILE_ORDER_PATH, PROFILES_DIR
from .utils import load_json


DEFAULT_PROFILE_ORDER = {
    "profilesDirectory": "profiles",
    "loadOrder": [
        "doskey-core.json",
        "doskey-personal.json"
    ]
}


def is_ignored_profile_file(profile_name):
    return profile_name.startswith("_") or profile_name.startswith(".")


def find_notepad():
    candidates = [
        Path(r"C:\Program Files\Notepad++\notepad++.exe"),
        Path(r"C:\Program Files (x86)\Notepad++\notepad++.exe"),
        Path(r"C:\Windows\notepad.exe"),
    ]
    for candidate in candidates:
        if candidate.exists():
            return str(candidate)
    return "notepad"


def alias_context():
    return {
        "app": str(APP_DIR),
        "profiles": str(PROFILES_DIR),
        "manager": str(LOADER_PATH),
        "loader": str(LOADER_PATH),
        "notepad": find_notepad(),
        "commandPrefix": command_prefix(),
    }


def load_profile_order():
    order_config = load_json(PROFILE_ORDER_PATH, DEFAULT_PROFILE_ORDER)
    profiles_dir = APP_DIR / order_config.get("profilesDirectory", "profiles")
    load_order = [
        profile_file
        for profile_file in order_config.get("loadOrder", [])
        if not is_ignored_profile_file(Path(profile_file).name)
    ]
    known_profiles = {Path(profile_file).name.lower() for profile_file in load_order}

    if profiles_dir.exists():
        for profile_path in profiles_dir.glob("*.json"):
            if is_ignored_profile_file(profile_path.name) or profile_path.name.lower() in known_profiles:
                continue
            load_order.append(profile_path.name)
            known_profiles.add(profile_path.name.lower())

    return profiles_dir, load_order


def load_profile(profile_path):
    data = load_json(profile_path, {})
    if "profiles" in data:
        profiles = data.get("profiles", {})
        return [
            {
                "name": profile_name,
                "description": profile.get("description", ""),
                "aliases": profile.get("aliases", []),
                "source": profile_path.name,
            }
            for profile_name, profile in profiles.items()
        ]

    return [
        {
            "name": data.get("name") or profile_path.stem,
            "description": data.get("description", ""),
            "aliases": data.get("aliases", []),
            "source": profile_path.name,
        }
    ]


def load_aliases():
    profiles_dir, load_order = load_profile_order()
    context = alias_context()
    by_name = {}
    ordered = []

    for profile_file in load_order:
        profile_path = profiles_dir / profile_file
        if not profile_path.exists():
            continue

        for profile in load_profile(profile_path):
            profile_name = profile["name"]
            for alias in profile.get("aliases", []):
                raw_alias_name = alias.get("name")
                command = alias.get("command")
                if not raw_alias_name or not command:
                    continue

                alias_name = str(raw_alias_name).format(**context)
                if not alias_name:
                    continue

                resolved = dict(alias)
                resolved["name"] = alias_name
                resolved["profile"] = profile_name
                resolved["command"] = command.format(**context)

                if alias_name not in by_name:
                    ordered.append(alias_name)
                by_name[alias_name] = resolved

    return [by_name[name] for name in ordered]


def emit_aliases(output=None):
    lines = [
        "@echo off",
        "REM Generated by DOSKEY Manager. Edit profiles/*.json or profiles.json instead.",
    ]
    for alias in load_aliases():
        lines.append(f"DOSKEY {alias['name']}={alias['command']}")

    text = "\n".join(lines) + "\n"
    if output:
        with open(output, "w", encoding="utf-8", newline="\n") as file:
            file.write(text)
    else:
        print(text, end="")


def print_aliases():
    aliases = load_aliases()
    if not aliases:
        print("No aliases are enabled.")
        return

    width = max(len(alias["name"]) for alias in aliases)
    current_profile = None
    for alias in aliases:
        if alias["profile"] != current_profile:
            current_profile = alias["profile"]
            print(f"\n[{current_profile}]")
        help_text = alias.get("help", "")
        print(f"  {alias['name'].ljust(width)}  {help_text}")
